#!/usr/bin/env python3
"""DS-side math parity: records the probe invocations of the three parity tests (first N cases of each), runs them
on the host probe, and writes
  tests/ds_selftest/cases.h      the argv lists, compiled into the self-test ROM
  build/ds_selftest/expected.txt the output of the host probe built with -DTT_XMATH (the DS's math) for the same cases
The self-test ROM (make selftest) runs the same core code on the emulated ARM9 and prints its output to the debug
port; tests/ds_selftest/run.py compares the two. Usage: gen_cases.py [world_cases] [ai_cases] [battle_cases]"""
import os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
sys.path.insert(0, os.path.join(ROOT, "tests", "parity"))
nw, na, nb = (int(x) for x in (sys.argv[1:] + ["60", "24", "2"][len(sys.argv) - 1:])[:3])

recorded = []
real_run = subprocess.run
def spy(args, **kw):
    if args and str(args[0]).endswith("probe"):
        recorded.append([str(a) for a in args[1:]])
    return real_run(args, **kw)
subprocess.run = spy

import run_parity, run_ai_parity, run_battle_parity  # noqa: E402
for mod, n in ((run_parity, nw), (run_ai_parity, na), (run_battle_parity, nb)):
    sys.argv = ["x", str(n)]
    mod.main()

os.makedirs(os.path.join(ROOT, "build", "ds_selftest"), exist_ok=True)
with open(os.path.join(ROOT, "build", "ds_selftest", "expected.txt"), "w") as f:
    for args in recorded:
        out = real_run([os.path.join(ROOT, "build", "host", "probe_xmath")] + args, capture_output=True, text=True, check=True).stdout
        f.write(out)
        f.write("CASE_END\n")
with open(os.path.join(HERE, "cases.h"), "w") as f:
    f.write("/* generated by gen_cases.py */\n")
    for i, args in enumerate(recorded):
        f.write("static const char *const C%d[] = {\"probe\", %s, 0};\n" % (i, ", ".join('"%s"' % a for a in args)))
    f.write("static const char *const *const CASES[] = {%s};\n" % ", ".join("C%d" % i for i in range(len(recorded))))
    f.write("#define NCASES %d\n" % len(recorded))
print(f"{len(recorded)} cases recorded")
