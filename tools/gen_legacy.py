#!/usr/bin/env python3
"""Generates core/gen/legacy_v1.c: how to read a save written by Terminal Tanks DS 1.5.0 (save version 1).

Version-1 saves store unlocks, tanks, ammo, maps, home screens, paints and Workshop parts by their POSITION in the
1.5.0 content lists. 2.0 inserts new content into those lists, so every position is remapped here BY NAME (old key ->
new index). Anything that no longer exists maps to -1 and is dropped safely. The 1.5.0 game is read from this repo's
history (the commit that imported the 1.5.0 port), so the table can always be rebuilt.
Run:  python3 tools/gen_legacy.py"""
import importlib.util, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
LEGACY_COMMIT = "03a67f1"          # "Import the Terminal Tanks DS source (v1.5.0 port ...)"
sys.path.insert(0, HERE)
import ttref  # noqa: E402

os.environ.setdefault("TT_NOAUDIO", "1")
src = subprocess.run(["git", "-C", ROOT, "show", f"{LEGACY_COMMIT}:reference/terminaltanks.py"], capture_output=True, check=True).stdout
tmp = os.path.join(tempfile.mkdtemp(), "tt150.py")
open(tmp, "wb").write(src)
spec = importlib.util.spec_from_file_location("tt150", tmp)
old = importlib.util.module_from_spec(spec)
sys.modules["tt150"] = old
spec.loader.exec_module(old)
new = ttref.load()


def lists(tt):
    """The content lists exactly as gen_content.py orders them (index = what a save stores)."""
    def maps_all():
        return list(tt.MAPS) + list(tt.SPECIAL_MAPS)
    turrets = getattr(tt, "_TURRETS", None) or tt.TURRETS
    hulls = getattr(tt, "_HULLS", None) or tt.HULLS
    tracks = getattr(tt, "_TRACKS", None) or tt.TRACKS
    return {
        "uid": [u.uid for u in tt.unlockables()] + ["ticket", "timemachine"],
        "design": [d.key for d in tt.ALL_DESIGNS],
        "ammo": [a.key for a in list(tt.ALL_AMMOS) + list(tt.MAGE_AMMO.values())],
        "map": [m.key for m in maps_all()],
        "home": list(tt.HOME_ORDER),
        "color": [n for n, _ in tt.COLOR_CHOICES],
        "barrel": list(tt.BARRELS),
        "glow": list(tt.GLOW_STYLES),
        "amb": list(tt.AMBIENT_KINDS),
        "turret": list(turrets),
        "hull": list(hulls),
        "track": list(tracks),
    }


O, N = lists(old), lists(new)
out = ["/* GENERATED by tools/gen_legacy.py - do not edit. Remaps a 1.5.0 (save version 1) save onto 2.0 content. */",
       '#include "../save_legacy.h"', ""]
hdr = []
for k in O:
    idx = {v: i for i, v in enumerate(N[k])}
    m = [idx.get(v, -1) for v in O[k]]
    lost = [v for v, j in zip(O[k], m) if j < 0]
    assert not lost or k == "uid", (k, lost)                     # every 1.5.0 item still exists in 2.0
    out.append(f"const short LEGACY_V1_{k.upper()}[{len(m)}] = {{" + ", ".join(map(str, m)) + "};")
    hdr.append(f"#define LEGACY_V1_N_{k.upper()} {len(m)}")
    hdr.append(f"extern const short LEGACY_V1_{k.upper()}[{len(m)}];")
    moved = sum(1 for i, j in enumerate(m) if i != j)
    print(f"{k:7s} {len(O[k]):4d} -> {len(N[k]):4d}   {moved:4d} moved   {len(lost)} gone {lost[:5]}")
hdr.append(f"#define LEGACY_V1_N_UNLOCKABLES {len(old.unlockables())}")
open(os.path.join(ROOT, "core", "gen", "legacy_v1.c"), "w").write("\n".join(out) + "\n")
open(os.path.join(ROOT, "core", "gen", "legacy_v1.h"), "w").write(
    "/* GENERATED by tools/gen_legacy.py - do not edit. */\n#ifndef TT_LEGACY_V1_H\n#define TT_LEGACY_V1_H\n" + "\n".join(hdr) + "\n#endif\n")
