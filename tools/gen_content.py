def enum(name, values, prefix):
    H(f"enum {{ " + ", ".join(f"{prefix}_{ident(v) if v else 'NONE'}" for v in values) + f", {prefix}_COUNT }};")
    C(f"const char *const {name}[{len(values)}] = {{" + ", ".join(cstr(v) for v in values) + "};")
    H(f"extern const char *const {name}[{len(values)}];")
    return {v: i for i, v in enumerate(values)}


