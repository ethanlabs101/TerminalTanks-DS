def cstr(s):
    if s is None:
        return "NULL"
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("".join("\\x%02x" % b for b in ch.encode("utf-8")) + '""')
    return '"' + "".join(out) + '"'


